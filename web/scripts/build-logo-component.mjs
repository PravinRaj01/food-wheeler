// Regenerates components/logo.tsx from assets/logo-mark.svg. Run this again
// whenever the source mark changes. Keeps every path's own fill color
// (the faceted/gem look), rather than collapsing to one recolorable
// currentColor - that shading is the point of this mark.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(path.join(root, "assets", "logo-mark.svg"), "utf8");
const inner = src.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();

const out = `// AUTO-GENERATED by scripts/build-logo-component.mjs from assets/logo-mark.svg.
// Do not hand-edit the paths below - change the source SVG and regenerate.
import type { SVGProps } from "react";

export function Logo(props: SVGProps<SVGSVGElement>) {
  return (
    <svg viewBox="0 0 256 255" xmlns="http://www.w3.org/2000/svg" {...props}>
${inner
  .split(/(?<=\/>)\s*(?=<path)/)
  .map((p) => "      " + p.trim())
  .join("\n")}
    </svg>
  );
}
`;

writeFileSync(path.join(root, "components", "logo.tsx"), out);
console.log("wrote components/logo.tsx");
